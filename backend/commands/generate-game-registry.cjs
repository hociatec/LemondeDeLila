#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(target);
    return entry.name === 'game.ts' || entry.name === 'game.json' ? [target] : [];
  });
}

function generateGameRegistry(options = {}) {
  const sourceRoot = options.sourceRoot ?? path.resolve(__dirname, '..', 'src', 'game');
  const gamesRoot = path.join(sourceRoot, 'games');
  const output = path.join(sourceRoot, 'composition', 'generated-game-registry.ts');
  const games = walk(gamesRoot).sort();
  const catalogIndex = games.map(file => ({
    code: path.basename(path.dirname(file)),
    directory: path.relative(gamesRoot, path.dirname(file)).replaceAll(path.sep, '/'),
  }));
  const codes = new Set();
  for (const file of games) {
    const directory = path.dirname(file);
    const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8').replace(/^\uFEFF/, ''));
    if (manifest.code !== path.basename(directory) || manifest.engine !== manifest.code || codes.has(manifest.code)) {
      throw new Error(`Identité de manifeste invalide ou dupliquée : ${directory}`);
    }
    if (!fs.existsSync(path.join(directory, 'rules.md'))) throw new Error(`rules.md manquant : ${directory}`);
    codes.add(manifest.code);
  }
  const imports = games.map((file, index) => {
    const relative = path
      .relative(path.dirname(output), file)
      .replaceAll(path.sep, '/')
      .replace(/\.(?:ts|json)$/, '');
    const target = relative.startsWith('.') ? relative : `./${relative}`;
    if (file.endsWith('game.json')) {
      return `import manifest${index} from '${target.replace(/\/game$/, '/manifest.json')}';\nimport document${index} from '${target}.json';`;
    }
    return `import game${index} from '${target}';\nimport manifest${index} from '${target.replace(/\/game$/, '/manifest.json')}';`;
  });
  const jsonGames = games.flatMap((file, index) => file.endsWith('game.json')
    ? [`const game${index} = compileJsonGame(manifest${index}, document${index});`] : []);
  if (jsonGames.length) imports.unshift("import { compileJsonGame } from '../engine/json/public-api';");
  const entries = games.map((file, index) => `  game${index},`);
  const packages = games.map((file, index) => `  Object.freeze({ definition: game${index}, manifest: manifest${index} }),`);
  const source = `${[...imports, ...jsonGames].join('\n')}

/** Generated by commands/generate-game-registry.cjs. Do not edit manually. */
export const GENERATED_GAME_DEFINITIONS: readonly unknown[] = Object.freeze([
${entries.join('\n')}
]);

export const GENERATED_GAME_PACKAGES: readonly {
  definition: unknown;
  manifest: unknown;
}[] = Object.freeze([
${packages.join('\n')}
]);
`;
  fs.writeFileSync(output, source, 'utf8');
  const indexOutput = path.join(sourceRoot, 'core/infrastructure/system/generated-game-catalog-index.json');
  fs.mkdirSync(path.dirname(indexOutput), {recursive: true});
  fs.writeFileSync(indexOutput, JSON.stringify(catalogIndex, null, 2) + '\n', 'utf8');
  return games.length;
}

if (require.main === module) {
  const count = generateGameRegistry();
  console.log(`Registry de jeux générée: ${count} définition(s).`);
}

module.exports = { generateGameRegistry };
