#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(target);
    return entry.name === 'game.ts' ? [target] : [];
  });
}

function generateGameRegistry(options = {}) {
  const sourceRoot = options.sourceRoot ?? path.resolve(__dirname, '..', 'src', 'game');
  const gamesRoot = path.join(sourceRoot, 'games');
  const output = path.join(sourceRoot, 'composition', 'generated-game-registry.ts');
  const games = walk(gamesRoot).sort();
  const imports = games.map((file, index) => {
    const relative = path
      .relative(path.dirname(output), file)
      .replaceAll(path.sep, '/')
      .replace(/\.ts$/, '');
    return `import game${index} from '${relative.startsWith('.') ? relative : `./${relative}`}';`;
  });
  const entries = games.map((_file, index) => `  game${index},`);
  const source = `${imports.join('\n')}

/** Generated by commands/generate-game-registry.cjs. Do not edit manually. */
export const GENERATED_GAME_DEFINITIONS: readonly unknown[] = Object.freeze([
${entries.join('\n')}
]);
`;
  fs.writeFileSync(output, source, 'utf8');
  return games.length;
}

if (require.main === module) {
  const count = generateGameRegistry();
  console.log(`Registry de jeux générée: ${count} définition(s).`);
}

module.exports = { generateGameRegistry };
