'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { scopeDirectory } = require('../tools/effect-pack-layout.cjs');

function validateIntroduction(name, profile, reference, readReview) {
  if (reference.effectPacks.includes(name)) return;
  const review = profile.introductionReview;
  if (
    !review ||
    !Array.isArray(review.existingMechanisms) ||
    !review.existingMechanisms.length ||
    review.existingMechanisms.some(
      (value) => typeof value !== 'string' || !value.trim(),
    ) ||
    typeof review.insufficiency !== 'string' ||
    review.insufficiency.trim().length < 120 ||
    typeof review.adr !== 'string' ||
    !/^docs\/architecture\/adr-.+\.md$/.test(review.adr) ||
    !readReview(review.adr) ||
    typeof review.test !== 'string' ||
    !/^src\/game\/.+\.spec\.ts$/.test(review.test) ||
    !readReview(review.test)
  )
    throw new Error(
      `${name}: a new effect-pack requires reviewed existing mechanisms, their insufficiency, an ADR and an executable test`,
    );
}

function renderRegistry(policy, reference, readReview) {
  const names = policy.registrationOrder;
  if (
    !Array.isArray(names) ||
    new Set(names).size !== names.length ||
    JSON.stringify([...names].sort()) !==
      JSON.stringify(Object.keys(policy.profiles).sort())
  )
    throw new Error(
      'The registration order must contain every classified effect-pack exactly once',
    );
  const identifier = (name) =>
    name.replace(/-([a-z])/g, (_match, letter) => letter.toUpperCase()) +
    'EffectPack';
  for (const name of names) {
    if (!/^[a-z]+(?:-[a-z]+)+$/.test(name))
      throw new Error('Invalid effect-pack name');
    validateIntroduction(name, policy.profiles[name], reference, readReview);
  }
  return [
    '// Generated by commands/generate-effect-pack-registry.cjs. Do not edit.',
    "import type { JsonEffectPackDomain } from '../../engine/sdk/extension-api';",
    ...names.map((name) => {
      const folder = scopeDirectory(policy.profiles[name].scope);
      return `import { effectPack as ${identifier(name)} } from '../${folder}/${name}/effect-pack';`;
    }),
    '',
    '/** Deterministic composition root. No filesystem discovery occurs at runtime. */',
    'export const jsonEffectPacks = Object.freeze([',
    ...names.map((name) => `  ${identifier(name)},`),
    '] as const);',
    '',
    'export type RegisteredJsonEffectPack = (typeof jsonEffectPacks)[number];',
    'type EffectPacksByDomain = Readonly<',
    '  Partial<Record<JsonEffectPackDomain, readonly RegisteredJsonEffectPack[]>>',
    '>;',
    'export const jsonEffectPacksByDomain: EffectPacksByDomain = (() => {',
    '  const domains = new Map<JsonEffectPackDomain, RegisteredJsonEffectPack[]>();',
    '  for (const pack of jsonEffectPacks) {',
    '    const members = domains.get(pack.domain) ?? [];',
    '    members.push(pack);',
    '    domains.set(pack.domain, members);',
    '  }',
    '  return Object.freeze(',
    '    Object.fromEntries(',
    '      [...domains].map(([domain, packs]) => [domain, Object.freeze(packs)]),',
    '    ),',
    '  );',
    '})();',
    '',
  ].join('\n');
}

function generateEffectPackRegistry({
  root = path.resolve(__dirname, '..'),
  check = false,
} = {}) {
  const policy = JSON.parse(
    fs.readFileSync(
      path.join(root, 'tools/engine-effect-pack-governance.json'),
      'utf8',
    ),
  );
  const reference = JSON.parse(
    fs.readFileSync(
      path.join(root, 'tools/engine-language-reference.json'),
      'utf8',
    ),
  );
  const readReview = (relative) => {
    const file = path.resolve(root, relative);
    return (
      file.startsWith(root + path.sep) &&
      fs.existsSync(file) &&
      fs.statSync(file).isFile() &&
      fs.readFileSync(file, 'utf8').trim().length >= 120
    );
  };
  const output = path.join(
    root,
    'src/game/rules/effect-packs/json-effect-pack-registry.ts',
  );
  const content = renderRegistry(policy, reference, readReview);
  const current = fs.existsSync(output)
    ? fs.readFileSync(output, 'utf8').replaceAll('\r\n', '\n')
    : '';
  if (check && current !== content)
    throw new Error(
      'Effect-pack registry is stale: run npm run effects:registry',
    );
  if (!check && current !== content) fs.writeFileSync(output, content);
}

module.exports = {
  validateIntroduction,
  renderRegistry,
  generateEffectPackRegistry,
};
if (require.main === module) {
  generateEffectPackRegistry({ check: process.argv.includes('--check') });
}
